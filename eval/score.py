"""Scores prediction files against the gold spans and writes report.md.

Two scorings, same rules for every system:
- overlap: a gold span counts as found when any prediction overlaps it (was it masked at all?).
  `full` additionally requires the predictions to cover every character of the gold span.
- exact: prediction boundaries and family both equal the gold span.
Precision ignores predictions that only touch `ignored` gold labels (out-of-scope label types).
A prediction contained in a longer prediction of the same system is dropped first (Presidio's own
anonymizer resolves overlaps the same way).
"""
import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).parent
STRUCTURED = {"EMAIL", "PHONE", "ID_NUMBER", "CARD", "ACCOUNT"}
SYSTEMS = [
    ("Presidio (spaCy lg)", "presidio"),
    ("Ours: rules only", "engine_regex"),
    ("Ours: rules + GLiNER", "engine_gliner"),
    ("Ours: rules + GLiNER + Gemini Nano", "engine_full"),
]


def load(path):
    return {d["id"]: d for d in map(json.loads, path.read_text(encoding="utf-8").splitlines())}


def overlaps(a, b):
    return a["start"] < b["end"] and b["start"] < a["end"]


def same_family(pred, gold):
    return pred["family"] == gold["family"] or (pred["family"] == "DATE" and gold["family"] == "DOB")


def trim(text, s):
    st, en = s["start"], s["end"]
    while st < en and text[st].isspace():
        st += 1
    while en > st and text[en - 1].isspace():
        en -= 1
    return st, en


def dedupe(preds):
    out = []
    for p in preds:
        if any(q is not p and q["start"] <= p["start"] and p["end"] <= q["end"]
               and (q["end"] - q["start"]) > (p["end"] - p["start"]) for q in preds):
            continue
        out.append(p)
    return out


def score(gold_docs, pred_docs):
    c = defaultdict(int)
    fam = defaultdict(lambda: defaultdict(int))
    # Scope = the families this dataset annotates. A prediction of any other family (our MEDICAL and
    # FINANCIAL on Nemotron; Presidio's URL, IP and plain dates) is not scored unless it hits a gold span.
    scope = {g["family"] for d in gold_docs.values() for g in d["gold"]}
    for doc_id, d in gold_docs.items():
        if doc_id not in pred_docs:
            continue  # system was run on a subset (the slow Nano configuration)
        c["docs"] += 1
        text = d["text"]
        preds = dedupe(pred_docs[doc_id]["preds"])
        for g in d["gold"]:
            hit = [p for p in preds if overlaps(p, g)]
            covered = set()
            for p in hit:
                covered.update(range(max(p["start"], g["start"]), min(p["end"], g["end"])))
            need = {i for i in range(g["start"], g["end"]) if not text[i].isspace()}
            found = bool(hit)
            full = found and need <= covered
            exact = any(trim(text, p) == trim(text, g) and same_family(p, g) for p in preds)
            c["gold"] += 1
            c["found"] += found
            c["full"] += full
            c["exact"] += exact
            f = fam[g["family"]]
            f["gold"] += 1
            f["found"] += found
            f["full"] += full
            f["exact"] += exact
            if g["family"] in STRUCTURED:
                c["s_gold"] += 1
                c["s_found"] += found
                c["s_full"] += full
        for p in preds:
            on_gold = any(overlaps(p, g) for g in d["gold"])
            on_ignored = any(overlaps(p, g) for g in d["ignored"])
            if not on_gold and (on_ignored or p["family"] not in scope):
                continue  # out-of-scope label or family: neither right nor wrong
            c["pred"] += 1
            c["pred_ok"] += on_gold
            c["pred_exact"] += any(trim(text, p) == trim(text, g) and same_family(p, g) for g in d["gold"])
    return c, fam


def prf(tp_recall, gold, tp_prec, pred):
    r = tp_recall / gold if gold else 0.0
    p = tp_prec / pred if pred else 0.0
    f = 2 * p * r / (p + r) if p + r else 0.0
    return p, r, f


def pct(x):
    return f"{x * 100:.1f}%"


lines = ["# Detection evaluation", ""]
lines += [
    "Generated by `eval/score.py`. Method and caveats are in `eval/README.md`.",
    "",
]
summary = {}
for lang, title in [("en", "English: NVIDIA Nemotron-PII test split, 300 documents (seeded sample)"),
                    ("zh", "Traditional Chinese: 30 synthetic samples written for this project")]:
    gold = load(HERE / f"data/{lang}.jsonl")
    n_gold = sum(len(d["gold"]) for d in gold.values())
    lines += [f"## {title}", "", f"{len(gold)} documents, {n_gold} in-scope gold spans.", ""]
    lines += ["| System | Overlap P | Overlap R | Overlap F1 | Fully covered R | Exact P | Exact R | Exact F1 | Structured R (overlap / full) |",
              "|---|---|---|---|---|---|---|---|---|"]
    fams = {}
    for name, key in SYSTEMS:
        path = HERE / f"out/{key}_{lang}.jsonl"
        if not path.exists():
            continue
        c, fam = score(gold, load(path))
        op, orr, of = prf(c["found"], c["gold"], c["pred_ok"], c["pred"])
        ep, er, ef = prf(c["exact"], c["gold"], c["pred_exact"], c["pred"])
        sr = c["s_found"] / c["s_gold"] if c["s_gold"] else 0
        sf = c["s_full"] / c["s_gold"] if c["s_gold"] else 0
        if c["docs"] < len(gold):
            name = f"{name} (first {c['docs']} documents only)"
        lines.append(f"| {name} | {pct(op)} | {pct(orr)} | {pct(of)} | {pct(c['full'] / c['gold'])} | {pct(ep)} | {pct(er)} | {pct(ef)} | {pct(sr)} / {pct(sf)} |")
        fams[name] = fam
        summary[(lang, key)] = {"overlap_f1": of, "exact_f1": ef, "structured_recall": sr, "structured_full": sf, "overlap_recall": orr}
    lines += ["", "Recall by family (overlap / fully covered / exact):", ""]
    names = list(fams)
    all_f = sorted({f for fam in fams.values() for f in fam}, key=lambda f: -max(fam[f]["gold"] for fam in fams.values()))
    lines += ["| Family | Gold | " + " | ".join(names) + " |", "|---|---|" + "---|" * len(names)]
    for f in all_f:
        g = max(fam[f]["gold"] for fam in fams.values())
        cells = []
        for n in names:
            x = fams[n][f]
            xg = x["gold"]
            cells.append(f"{pct(x['found'] / xg)} / {pct(x['full'] / xg)} / {pct(x['exact'] / xg)}" if xg else "-")
        lines.append(f"| {f} | {g} | " + " | ".join(cells) + " |")
    lines.append("")

(HERE / "out/summary.json").write_text(json.dumps({f"{k[0]}:{k[1]}": v for k, v in summary.items()}, indent=1), encoding="utf-8")
(HERE / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
